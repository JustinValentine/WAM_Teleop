"""Write a fit as the controller's parameter header (cable_params_*.h) and a
JSON record."""
import datetime
import json

import numpy as np

from . import model as M


def _arr(v):
    return '{' + ', '.join('%.12g' % x for x in v) + '}'


def theta_dict(theta, labels):
    return {l: float(v) for l, v in zip(labels, theta)}


def header(arm, spec, theta, labels, namespace, note):
    t = theta_dict(theta, labels)
    assert spec.friction == 'cable', 'the controller runs the cable model only'
    K = len(spec.motor_deltas)
    beta = np.zeros(30)
    beta[M.RB_COLS] = theta[:22]
    mw = [[t['ms_m%d_%d' % (m + 1, i)] for i in range(K)] for m in range(4)]
    jw = [[t['ms_j%d_%d' % (j, i)] for i in range(len(spec.joint_deltas))] for j in (2, 3)]
    visc = [t['fv_m%d' % (m + 1)] for m in range(4)]
    rot = [t.get('Ia_m%d' % (m + 1), 0.0) for m in range(4)]
    off = [t.get('off_j%d' % (j + 1), 0.0) for j in range(4)]
    lines = []
    lines.append('// Generated by ident/ (python -m cable_ident fit --arm %s) on %s. Do not edit.' % (
        arm, datetime.date.today().isoformat()))
    for l in note.splitlines():
        lines.append('// ' + l)
    lines += ['#pragma once', '', '#include "cable_drive_model.h"', '',
              'namespace %s {' % namespace, '',
              'static_assert(cable_model::KM == %d && cable_model::KJ == %d, "regenerate: element counts changed");'
              % (K, len(spec.joint_deltas)), '',
              'inline cable_model::Params params() {',
              '\tcable_model::Params p = {',
              '\t\t%s,  // beta (regressor_W.h; friction slots 0)' % _arr(beta),
              '\t\t{%s},  // TM' % ', '.join(_arr(r) for r in M.TM),
              '\t\t%s,  // motor slip displacements (rad)' % _arr(spec.motor_deltas),
              '\t\t{%s},  // motor slip forces (Nm)' % ', '.join(_arr(r) for r in mw),
              '\t\t%s,  // J2/J3 slip displacements (rad)' % _arr(spec.joint_deltas),
              '\t\t{%s},  // J2/J3 slip forces (Nm)' % ', '.join(_arr(r) for r in jw),
              '\t\t%s,  // motor viscous (Nm s/rad)' % _arr(visc),
              '\t\t%s,  // motor rotors (kg m^2)' % _arr(rot),
              '\t\t%s,  // offsets (Nm)' % _arr(off),
              '\t};', '\treturn p;', '}', '',
              '}  // namespace %s' % namespace, '']
    return '\n'.join(lines)


def record(path, **kw):
    def conv(o):
        if isinstance(o, np.ndarray):
            return o.tolist()
        if isinstance(o, (np.floating, np.integer)):
            return o.item()
        return str(o)
    with open(path, 'w') as f:
        json.dump(kw, f, indent=1, default=conv)
